// Base URL for the static dataset bundles under public/datasets/. Defaults to ''
// (same-origin), so bundles ship from the app host. Set VITE_BUNDLE_BASE_URL at
// build time (e.g. a Cloudflare R2 / CDN origin like https://cdn.example.com) to
// serve the bundles off-origin with zero code changes — the meta/qc/track loaders
// all prepend dataset.bundleBaseUrl.
//
// The value and its trailing-slash normalization live in ./bundleBase, so there
// is ONE definition of where bundles are served from: every dataset's
// bundleBaseUrl below is a projection of it rather than a rival authority.
const BUNDLE_BASE: string = BUNDLE_BASE_URL;

// The seven bundle-locator fields every dataset carries are pure functions of
// its id (verified across all 41 entries at introduction: zero deviations), so
// the factory derives them and an entry states only what actually differs per
// dataset. A future dataset that genuinely deviates can still override any of
// them — the ?? keeps an intentional `bundleBaseUrl: ''` valid.
type DerivableDatasetField =
  | 'bundleBaseUrl'
  | 'metaFile'
  | 'metaGlobalKey'
  | 'qcFile'
  | 'qcGlobalKey'
  | 'bundleFileTemplate'
  | 'globalKeyTemplate';

export type DatasetDefinition =
  Omit<Dataset, DerivableDatasetField> & Partial<Pick<Dataset, DerivableDatasetField>>;

export function defineDataset(input: DatasetDefinition): Dataset {
  const namespace = input.id.toUpperCase();
  return {
    ...input,
    bundleBaseUrl: input.bundleBaseUrl ?? BUNDLE_BASE,
    metaFile: input.metaFile ?? `/datasets/${input.id}/meta.js`,
    metaGlobalKey: input.metaGlobalKey ?? `HX_${namespace}_META`,
    qcFile: input.qcFile ?? `/datasets/${input.id}/qc_global.js`,
    qcGlobalKey: input.qcGlobalKey ?? `HX_${namespace}_QC`,
    bundleFileTemplate: input.bundleFileTemplate ?? `/datasets/${input.id}/track_{trackId}.js`,
    globalKeyTemplate: input.globalKeyTemplate ?? `HX_${namespace}_{TRACKID}`,
  };
}

// ── Bulk-study constructor ───────────────────────────────────────────────────
// The standard arm palette for every two-arm bulk study: baseline blue,
// case red. Named once; the macaque atlas and GSE135639 stay on defineDataset
// because they do not fit the single-track, single-default-contrast shape this
// constructor hides (multi-track atlas; factorial contrasts), not because their
// palettes differ.
const BASELINE_COLOR = '#3775BA';
const CASE_COLOR = '#B64342';

/** What a single-track, single-contrast, two-arm public-expression study
 *  (GEO or ArrayExpress) actually states.
 *  Everything else — gene features, pathways on, non-default, the 'track'
 *  noun, the ['Tissue'] category order, the CPM (TMM-normalized) unit, the standard arm
 *  palette, the lone default contrast — is policy, supplied here. */
export type BulkStudyDefinition =
  Pick<
    Dataset,
    | 'id'
    | 'category'
    | 'name'
    | 'organism'
    | 'modality'
    | 'region'
    | 'perturbation'
    | 'preparation'
    | 'citation'
  > &
    Required<Pick<Dataset, 'doi' | 'geo' | 'pmid'>> &
    Partial<Pick<Dataset, 'expressionUnit'>> & {
      /** The single (default) track id — also the bundle's track file name. */
      track: string;
      /** Arm display labels. Group keys default to 'control'/'case'; override
       *  `keys` only when the bundle's groupSamples use different keys. */
      arms: {
        baseline: string;
        case: string;
        keys?: [baselineKey: string, caseKey: string];
      };
      /** Id of the single default contrast (e.g. 'hfd_vs_chow'). */
      contrast: string;
      /** Optional reader-facing qualifiers for that contrast (see Contrast):
       *  a description, and `exploratory` when the comparison must be read as
       *  exploratory (drives the study-bar warning beside the volcano). */
      contrastNote?: Pick<Contrast, 'description' | 'exploratory'>;
      /** Time-series descriptor; `tracks` is derived as `[track]`, since a
       *  bulk study's lone track is by construction the rhythmic one. */
      timeSeries?: Omit<TimeSeriesDescriptor, 'tracks'>;
    };

/** Registry constructor for the standard bulk/translatome study shape. */
export function defineBulkStudy(input: BulkStudyDefinition): Dataset {
  const { track, arms, contrast, contrastNote, expressionUnit, timeSeries, ...study } = input;
  const [baselineKey, caseKey] = arms.keys ?? ['control', 'case'];
  return defineDataset({
    ...study,
    featureType: 'gene',
    featureLabel: 'Gene',
    expressionUnit: expressionUnit ?? CPM_TMM_UNIT,
    supportsPathways: true,
    isDefault: false,
    defaultTrack: track,
    trackNoun: 'track',
    trackCategoryOrder: ['Tissue'],
    groups: [
      { key: baselineKey, label: arms.baseline, color: BASELINE_COLOR },
      { key: caseKey, label: arms.case, color: CASE_COLOR },
    ],
    contrasts: [{ id: contrast, baseline: baselineKey, case: caseKey, isDefault: true, ...contrastNote }],
    ...(timeSeries ? { timeSeries: { tracks: [track], ...timeSeries } } : {}),
  });
}

