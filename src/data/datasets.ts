// Count inputs and model outputs must exist before the intake builder writes
// this registry sidecar. Candidate records alone never enter the explorer.
// september5Studies.generated.json is pinned by exact bytes in retained evidence,
// so it keeps the intake's pre-regeneration 'CPM' label. Since the R 4.6.0
// regeneration every one of those count studies ships the DE fit's TMM CPM
// (data/intake/regeneration-r460-2026-09-25.json), so the label is read here.
const regeneratedUnit = (study: DatasetDefinition): DatasetDefinition =>
  study.expressionUnit === 'CPM' ? { ...study, expressionUnit: CPM_TMM_UNIT } : study;
DATASETS.push(...SEPTEMBER5_STUDIES.map((study) =>
  defineDataset(reviewedStudyMetadata(regeneratedUnit(study as DatasetDefinition)))));
DATASETS.push(...HFD_STUDIES.map((study) => defineDataset(study as DatasetDefinition)));
DATASETS.push(...OXT_AVP_STUDIES.map((study) => defineDataset(study as DatasetDefinition)));

// ── Dataset categories ──────────────────────────────────────────────────────
// Category is a required field on each entry (type-checked), so a dataset can
// no longer be silently mis-stratified by an out-of-date side table.

/** Thematic category for a registered dataset id. Throws on an unknown id —
 *  a silent default once landed datasets under the wrong report heading. */
export function datasetCategory(id: string): DatasetCategory {
  const dataset = getDataset(id);
  if (!dataset) throw new Error(`datasetCategory: unknown dataset id "${id}"`);
  return dataset.category;
}

/** Datasets grouped by category in display order; empty categories are dropped. */
export function datasetsByCategory(
  list: Dataset[] = DATASETS,
): Array<{ category: DatasetCategory; datasets: Dataset[] }> {
  return DATASET_CATEGORIES.map((category) => ({
    category,
    datasets: list.filter((d) => d.category === category),
  })).filter((g) => g.datasets.length > 0);
}

export function listDatasets(): Dataset[] {
  return DATASETS;
}

export function getDataset(id: string): Dataset | null {
  return DATASETS.find((d) => d.id === id) || null;
}

export function getDefaultDataset(): Dataset {
  return DATASETS.find((d) => d.isDefault) || DATASETS[0];
}
