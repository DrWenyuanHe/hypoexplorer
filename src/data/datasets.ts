// Bundled dataset registry — the single source of truth for which datasets the
// explorer can browse. This is a BUNDLED ES module (imported, tree-shaken,
// testable), NOT a window global: it ships inside the JS bundle so no eager
// <script> tag is needed.
//
// Each manifest describes one study/modality (organism, modality, feature type,
// whether it supports pathway enrichment, citation), how to locate its bundles
// (file/global templates, base URL), its default track, the sidebar category
// order for its tracks, and its experimental groups + contrasts.
//
// Terminology (see docs/DATASET_CONTRACT.md):
//   dataset  — one study/modality
//   track    — the unit selected within a dataset (a cell population for
//              single-cell, or a whole-tissue track for bulk/miRNA)
//   group    — an experimental arm {key, label, color} (Normal, Obese, …)
//   contrast — a baseline→case comparison referencing two group keys
// Use defineBulkStudy for the standard two-arm bulk shape; defineDataset handles wider studies.

