// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { _resetTrackCache } from '../data/loadTrack';
import {
  loadTrackPathways, manifestSupportsTrackPathways, type QueryManifest, type TrackPathwayRow,
} from '../data/queryIndex';
import { trackPathwaysFile, trackPathwaysGlobal } from '../data/queryWire';
import { BULK_DATASET_FIXTURE } from './fixtures';

// The track-pathways family: one file per pathway-capable track under the
// build prefix, read by the search portal's condition-pathways card. A file is
// addressed by the track's MANIFEST POSITION, so the loader must refuse one
// whose build stamp or track identity disagrees with the manifest it was
// opened against: either pairing would list another track's pathways.

const DS = BULK_DATASET_FIXTURE;
const BUILD_ID = 'tpbuild1';

const MANIFEST: QueryManifest = {
  v: 2,
  buildId: BUILD_ID,
  geneShards: 512,
  pathwayShards: 256,
  dbNames: ['GO_BP', 'HALLMARK'],
  tracks: [
    { ds: DS.id, trackId: 'whole', label: 'Whole hypothalamus', type: 'Tissue', lowPower: false },
    { ds: DS.id, trackId: 'arcuate', label: 'Arcuate', type: 'Tissue', lowPower: false },
  ],
  trackPathways: { fdr: 0.05, tracks: [0, 1] },
};

const ROWS: TrackPathwayRow[] = [
  ['HALLMARK_INFLAMMATORY_RESPONSE', 2.1, 0.0004, 180, 1, 2, 2],
  ['GOBP_FEEDING_BEHAVIOR', -1.7, 0.03, 64, 0, 1, 2],
];

/** The file exactly as scripts/build_query_index.mts writes it. */
function emitted(payload: unknown, global: string): string {
  return `// AUTO-GENERATED by scripts/build_query_index.mts — do not edit\n// test\nvar ${global} = ${JSON.stringify(payload)};\n`;
}

/** Serve `files` (URL substring -> emitted text); anything else 404s. */
function stubScripts(files: Record<string, string>) {
  const orig = document.createElement.bind(document);
  const requested: string[] = [];
  vi.spyOn(document, 'createElement').mockImplementation((tag: any) => {
    const el = orig(tag);
    if (tag === 'script') {
      setTimeout(() => {
        const src: string = el.src || '';
        requested.push(src);
        const hit = Object.keys(files).find((k) => src.includes(k));
        if (!hit) { el.onerror?.(new Event('error')); return; }
        const text = files[hit];
        const global = /var (\w+) = /.exec(text)![1];
        (window as any)[global] = JSON.parse(text.slice(text.indexOf('= ') + 2).replace(/;\s*$/, ''));
        el.onload?.(new Event('load'));
      }, 0);
    }
    return el;
  });
  return { requested };
}

beforeEach(() => { _resetTrackCache(); });
afterEach(() => {
  vi.restoreAllMocks();
  for (const i of [0, 1]) delete (window as any)[trackPathwaysGlobal(i)];
});

describe('track-pathways wire names', () => {
  it('pads the manifest position like every other shard name', () => {
    expect(trackPathwaysFile(7)).toBe('trackpaths/t007.js');
    expect(trackPathwaysGlobal(7)).toBe('HX_QUERY_TRACKPATHS_007');
    expect(trackPathwaysFile(1234)).toBe('trackpaths/t1234.js');
  });
});

describe('manifestSupportsTrackPathways', () => {
  it('needs the family at the client’s own cutoff', () => {
    expect(manifestSupportsTrackPathways(MANIFEST)).toBe(true);
    expect(manifestSupportsTrackPathways({ ...MANIFEST, trackPathways: undefined })).toBe(false);
    expect(manifestSupportsTrackPathways({ ...MANIFEST, trackPathways: { fdr: 0.1, tracks: [0] } })).toBe(false);
  });
});

describe('loadTrackPathways', () => {
  it('round-trips an emitted file into its rows, requesting only that track', async () => {
    const { requested } = stubScripts({
      [`/query/${BUILD_ID}/trackpaths/t001.js`]: emitted(
        { b: BUILD_ID, d: { ds: DS.id, trackId: 'arcuate', rows: ROWS } }, trackPathwaysGlobal(1),
      ),
    });
    await expect(loadTrackPathways([DS], MANIFEST, 1)).resolves.toEqual(ROWS);
    expect(requested).toHaveLength(1);
    expect(requested[0]).toContain(`/query/${BUILD_ID}/trackpaths/t001.js`);
  });

  it('reads an empty list as a measured none, not as unavailable', async () => {
    stubScripts({
      'trackpaths/t000.js': emitted({ b: BUILD_ID, d: { ds: DS.id, trackId: 'whole', rows: [] } }, trackPathwaysGlobal(0)),
    });
    await expect(loadTrackPathways([DS], MANIFEST, 0)).resolves.toEqual([]);
  });

  it('refuses a file stamped by another build', async () => {
    vi.spyOn(console, 'warn').mockImplementation(() => {});
    stubScripts({
      'trackpaths/t000.js': emitted({ b: 'otherbuild', d: { ds: DS.id, trackId: 'whole', rows: ROWS } }, trackPathwaysGlobal(0)),
    });
    await expect(loadTrackPathways([DS], MANIFEST, 0)).resolves.toBeNull();
  });

  it('refuses a file that names a different track than the manifest position', async () => {
    stubScripts({
      'trackpaths/t000.js': emitted({ b: BUILD_ID, d: { ds: DS.id, trackId: 'arcuate', rows: ROWS } }, trackPathwaysGlobal(0)),
    });
    await expect(loadTrackPathways([DS], MANIFEST, 0)).resolves.toBeNull();
  });

  it('resolves null, never rejects, when the file is missing or the position is out of range', async () => {
    stubScripts({});
    await expect(loadTrackPathways([DS], MANIFEST, 0)).resolves.toBeNull();
    await expect(loadTrackPathways([DS], MANIFEST, 9)).resolves.toBeNull();
  });
});
